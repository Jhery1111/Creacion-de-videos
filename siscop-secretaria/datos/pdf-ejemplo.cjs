// Genera el PDF ficticio que se adjunta en la escena de Nueva correspondencia.
const path = require('path')
const { createRequire } = require('module')
const req = createRequire(path.join(process.env.BACKEND, 'package.json'))
const PDFDocument = req('pdfkit')
const fs = require('fs')
const doc = new PDFDocument({ size: 'LETTER', margin: 64 })
doc.pipe(fs.createWriteStream(path.join(__dirname, 'CITE-DNTT-221-2026.pdf')))
doc.font('Helvetica-Bold').fontSize(13).text('POLICÍA BOLIVIANA', { align: 'center' })
doc.font('Helvetica').fontSize(10).text('DIRECCIÓN NACIONAL DE TECNOLOGÍA Y TELEMÁTICA', { align: 'center' }).moveDown(2)
doc.font('Helvetica-Bold').text('CITE: DNTT N° 221/2026').moveDown(0.4)
doc.font('Helvetica').text('La Paz, 4 de noviembre de 2026').moveDown(1.2)
doc.font('Helvetica-Bold').text('REF.: SOLICITUD DE INFORMACIÓN SOBRE EQUIPOS DE RADIOCOMUNICACIÓN').moveDown(1.2)
doc.font('Helvetica').fontSize(11).text('Documento de ejemplo para el tutorial de SISCOP.', { align: 'justify' })
doc.end()
